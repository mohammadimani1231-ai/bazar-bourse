/**
 * مرزهای مقیاس diverging نقشهٔ بازار — بخش ۲ bazar-bourse-dataviz-spec.md، نسخهٔ اصلاح‌شده
 * (کاربر بعد از دیدن بورس‌ویو داد، جای جدول قدیمی فایل را می‌گیرد):
 *   خنثی ±۰.۵٪ | ضعیف ۰.۵٪-۲٪ | متوسط ۲٪-۴٪ (نزدیک/روی سقف دامنهٔ رسمی ۳٪) | شدید بالای ۴٪
 *
 * نکتهٔ مهم دربارهٔ نگاشت به ۹ توکن رنگ: مرزهای «ضعیف/متوسط/شدید» بالا عیناً با مرزهای
 * تعریف‌شدهٔ پله‌های ۲/۳/۴ در جدول *قدیمی* همان فایل یکی است (۰.۵-۲٪ → پلهٔ ۲، ۲-۴٪ → پلهٔ ۳،
 * ≥۴٪ → پلهٔ ۴) — تنها تغییر واقعی این است که «خنثی» حالا رسماً ±۰.۵٪ تعریف شده (قبلاً «۰٪±
 * نزدیک صفر» مبهم بود) و پلهٔ ۱ قدیمی (۰ تا ۰.۵٪) کاملاً داخل همین خنثی جدید ادغام شده. یعنی
 * heat-neg-1/heat-pos-1 با این مرزهای جدید هرگز انتخاب نمی‌شوند — توکن‌هایشان طبق دستور کاربر
 * دست‌نخورده در globals.css می‌مانند، فقط این تابع دیگر صدایشان نمی‌زند.
 */
export function heatmapStepVar(changePct: number | null): string {
  if (changePct == null || Number.isNaN(changePct)) return "var(--heat-0)";

  const abs = Math.abs(changePct);
  if (abs <= 0.5) return "var(--heat-0)";

  const sign = changePct > 0 ? "pos" : "neg";
  if (abs <= 2) return `var(--heat-${sign}-2)`;
  if (abs <= 4) return `var(--heat-${sign}-3)`;
  return `var(--heat-${sign}-4)`;
}
